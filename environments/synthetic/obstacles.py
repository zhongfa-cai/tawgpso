def get_obstacle_base(name: str) -> tuple[ObstacleBase, ...]:
    key = str(name).strip().lower()
    if key not in OBSTACLE_SETS:
        valid = ", ".join(OBSTACLE_SETS)
        raise KeyError(f"Unknown synthetic environment {name!r}. Expected one of: {valid}.")
    return OBSTACLE_SETS[key]
